const squash = (text) => String(text ?? '').replace(/\s+/g, ' ').trim();

// Latin-script words inside Urdu text (C++, Python, GU TECH ...) are wrapped in "isolates" so the symbols stay in the right
// order: without them the bidirectional algorithm shows C++ as ++C. U+2066 starts a left-to-right island, U+2069 ends it.
const LATIN_RUN = /[A-Za-z][A-Za-z0-9+#./*&-]*(?: [A-Za-z][A-Za-z0-9+#./*&-]*)*/g;
export const isolateLatin = (text) => text.replace(LATIN_RUN, (run) => `⁦${run}⁩`);

/** True for text with English letters and no Arabic-script letters (Urdu): such a block is shown left to right. */
export const readsAsEnglish = (text) => /[A-Za-z]/.test(text) && !/[؀-ۿ]/.test(text);

/** The Urdu for a piece of English text (spacing is ignored), or null when there is none. */
export function urdu(text) {
  const key = squash(text);
  return Object.hasOwn(ur, key) ? isolateLatin(ur[key]) : null;
}
